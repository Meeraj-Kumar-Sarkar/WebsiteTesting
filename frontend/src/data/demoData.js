/**
 * Helper to resolve packages that cover a given stay.
 */
export function getPackagesForStay(stay, allPackages = demoPackages) {
  if (!stay) return [];
  const linkedIds = new Set(stay.packageIds || []);
  const matches = allPackages.filter((pkg) => {
    if (linkedIds.has(pkg.packageId) || linkedIds.has(pkg.id)) return true;
    if (Array.isArray(pkg.stayIds) && pkg.stayIds.includes(stay.id)) return true;
    const destText = `${pkg.states || ''} ${pkg.destinationName || ''} ${(pkg.destinations || []).join(' ')}`.toLowerCase();
    const stayLoc = (stay.destinationName || stay.location || '').toLowerCase().split(',')[0].trim();
    return stayLoc.length > 3 && destText.includes(stayLoc);
  });
  return matches.length > 0 ? matches : allPackages.slice(0, 2);
}
